export type Language = keyof typeof translations;
export type TranslationKey = keyof (typeof translations)['en'];

type I18nContextValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

let currentLanguage: Language = 'en';

function normalizeLanguage(value: string | null | undefined): Language {
  return value?.toLowerCase().startsWith('uk') ? 'uk' : 'en';
}

function readStoredLanguage(): Language {
  if (typeof window === 'undefined') {
    return 'en';
  }

  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (stored) {
    return normalizeLanguage(stored);
  }

  return normalizeLanguage(window.navigator.language);
}

function interpolate(template: string, params?: Record<string, string | number>) {
  if (!params) {
    return template;
  }

  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(params[key] ?? ''));
}

function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>) {
  return interpolate(translations[language][key], params);
}

function persistLanguage(language: Language) {
  currentLanguage = language;

  if (typeof window !== 'undefined') {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }
}

export function getLocaleForLanguage(language: Language) {
  return language === 'uk' ? 'uk-UA' : 'en-US';
}

export function translateStatic(key: TranslationKey, params?: Record<string, string | number>) {
  return translate(currentLanguage, key, params);
}

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<Language>(() => {
    const initialLanguage = readStoredLanguage();
    currentLanguage = initialLanguage;
    return initialLanguage;
  });

  const setLanguage = (nextLanguage: Language) => {
    persistLanguage(nextLanguage);
    setLanguageState(nextLanguage);
  };

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      locale: getLocaleForLanguage(language),
      setLanguage,
      t: (key, params) => translate(language, key, params),
    }),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);

  if (!value) {
    throw new Error('useI18n must be used within I18nProvider.');
  }

  return value;
}
